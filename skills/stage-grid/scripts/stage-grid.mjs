/**
 * Build the stage grid app for one period.
 *
 *   node stage-grid.mjs build [--quarter <slug>] [--graph f] [--config f] [--ladder f] [--out dir]
 *   node stage-grid.mjs show  [--quarter <slug>] [...]       the grid as text, for review
 *
 * Paths default to [suite.stage-grid] graph, config, ladder and out in
 * .agents/skill-bindings.toml, where {quarter} is replaced by --quarter. Writes
 * <out>/stage-grid-data.js, the one file the app reads, and copies the app (index.html,
 * stage-grid.js) beside it, so <out> opens from disk or is published as it is.
 *
 * Exit 0: done. Exit 1: built, with warnings, under --strict. Exit 2: usage error.
 */

import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {readBindings, boundPath} from './lib/bindings.mjs';
import {buildData, loadInputs} from './lib/grid.mjs';

const APP = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'app');
const USAGE = 'usage: stage-grid.mjs build|show [--quarter slug] [--graph file] [--config file] [--ladder file] [--out dir] [--strict]';

function parseArgs(argv) {
  const out = {_: []};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--strict' || a === '--help' || a === '-h') out[a.replace(/^-+/, '')] = true;
    else if (a.startsWith('--')) out[a.slice(2)] = argv[++i];
    else out._.push(a);
  }
  return out;
}

/** A path from the command line (relative to the working directory) or the bindings. */
function resolve(args, b, key) {
  const fill = (p) => (args.quarter ? p.split('{quarter}').join(args.quarter) : p);
  if (args[key]) return path.resolve(fill(args[key]));
  return b[key] ? boundPath(b, fill(b[key])) : null;
}

export function writeApp(data, out) {
  fs.mkdirSync(out, {recursive: true});
  const json = JSON.stringify(data, null, 1).split('<').join('\\u003c');
  fs.writeFileSync(path.join(out, 'stage-grid-data.js'), `// Generated by the stage-grid skill. Do not edit.\nwindow.STAGE_GRID = ${json};\n`);
  for (const f of ['index.html', 'stage-grid.js']) fs.copyFileSync(path.join(APP, f), path.join(out, f));
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const cmd = args._[0];
  if (args.help || args.h || !cmd) { console.log(USAGE); return cmd ? 0 : 2; }
  const b = readBindings(process.cwd(), 'stage-grid');
  const graphFile = resolve(args, b, 'graph');
  const configFile = resolve(args, b, 'config');
  for (const [k, f] of [['graph', graphFile], ['config', configFile]]) {
    if (!f || !fs.existsSync(f)) { console.error(f ? `${k} ${f}: not found` : `No ${k}: bind [suite.stage-grid] ${k}, or pass --${k}.`); return 2; }
  }
  const graph = JSON.parse(fs.readFileSync(graphFile, 'utf-8'));
  const {config, ladderRows, configDir} = loadInputs(configFile, {ladder: resolve(args, b, 'ladder')});
  const data = buildData(graph, config, {ladderRows, configDir});
  for (const w of data.warnings) console.error(`warning: ${w}`);

  if (cmd === 'show') {
    for (const lane of data.lanes) {
      console.log(`${lane.label} (${lane.id}): ${lane.epics.map((id) => data.epics[id].key || id).join(', ')}`);
      for (const s of data.stages) {
        const items = lane.cells[s.id].map((i) => i.label).concat(lane.outcomes.filter((o) => o.stage === s.id).map((o) => `[${o.status || 'outcome'}] ${o.text}`));
        if (items.length) console.log(`  ${s.n} ${s.name.padEnd(14)} ${items.join(' | ')}`);
      }
    }
    return 0;
  }
  if (cmd === 'build') {
    const out = resolve(args, b, 'out') || path.resolve('stage-grid');
    writeApp(data, out);
    const placed = data.lanes.reduce((n, l) => n + Object.values(l.cells).reduce((m, c) => m + c.length, 0), 0);
    console.log(`${data.stages.length} stages, ${data.lanes.length} lanes, ${Object.keys(data.epics).length} epics, ${placed} items placed -> ${path.relative(process.cwd(), out) || '.'}`);
    return args.strict && data.warnings.length ? 1 : 0;
  }
  console.error(USAGE);
  return 2;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main();
